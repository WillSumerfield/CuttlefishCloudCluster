import { useCallback, useEffect, useState } from "react";
import {
  getCredential,
  setCredential,
  mintCredential,
  deleteCredential,
  verifyGithub,
  Unauthorized,
  errMessage,
  type CredentialKind,
  type CredentialStatus,
  type GithubCheck,
} from "../api";
import { Tip } from "../app/Tip";

/**
 * One **Credential** module — a stored third-party secret, kept under the User's own password on the
 * Head and injected into every Spawn they submit from either client.
 *
 * **Write-only, and this component is the shape of that.** There is no Reveal: the Head has nothing to
 * reveal. What is shown afterwards is the `hint` it keeps in the clear beside the secret, which answers
 * the only question Reveal was really answering ("is this the key I meant?") without putting the secret
 * on the wire, in scrollback, or on the screen of whoever is standing behind you.
 *
 * Parameterised by `kind` rather than written per secret, mirroring `credentials.KINDS` on the Head:
 * adding a third secret is an entry in SPECS below, not a second copy of this file.
 *
 * **Two origins, and that is the only fork in here.** A *handed-over* Credential (the W&B key) is
 * pasted: it exists elsewhere first, and its hint is a shortened handle — enough to recognise, useless
 * to a thief. A *minted* one (the GitHub key) is generated by the Head, and its hint is the PUBLIC
 * half, shown in full, because pasting that into GitHub is the entire job. So the middle of this
 * component branches and the sixty lines around it — loading, errors, the header, the actions — do not.
 */

type Common = {
  label: string;
  /** What the Tip beside the label explains — why the Head is holding this at all. */
  tip: string;
  /** The line shown when nothing is stored yet. */
  invitation: string;
};

type PasteSpec = Common & {
  origin: "paste";
  placeholder: string;
  /** How the hint reads back. A W&B key is one opaque string, so a masked run + its tail. */
  masked: (hint: string) => string;
};

type MintSpec = Common & {
  origin: "mint";
  /** The verb on the button that creates one. Not "Save": nothing here is being handed over. */
  mintLabel: string;
  /** Where the public half has to be registered, and how to say so. */
  registerUrl: string;
  registerNote: string;
  /**
   * Ask the third party whether the public half has been registered yet. Optional, and per-kind rather
   * than baked in: it is the only part of this that talks to somewhere other than the Head, so a future
   * minted kind with nowhere to ask simply omits it and loses the button, not the module.
   */
  check?: () => Promise<GithubCheck>;
  /** What replacing and removing actually cost, named in the confirmation rather than "are you sure?". */
  replaceCost: string;
  removeCost: string;
};

type Spec = PasteSpec | MintSpec;

const SPECS: Record<CredentialKind, Spec> = {
  wandb: {
    origin: "paste",
    label: "W&B key",
    tip: "Held on the Head under your password and injected into every Spawn you submit, from either client — so your runs log to your own account whichever machine you launched them from. Nobody can read it back, including you.",
    placeholder: "paste your W&B API key",
    invitation: "Injected into every spawn you submit, from either client. Held under your password — nobody can read it back.",
    masked: (hint) => `•••••••••• ${hint}`,
  },
  github: {
    origin: "mint",
    label: "GitHub key",
    tip: "The Head generates this one — you never see the private half, and neither does anyone else. It is injected into every Spawn as a live ssh-agent, so `git clone` and `pip install git+ssh://` reach your private repos with no key on any disk. Add the public half to your GitHub account to switch it on.",
    invitation: "The Head mints an SSH key and keeps the private half under your password. You add the public half to GitHub — that is the only part you ever see.",
    mintLabel: "Mint a key",
    registerUrl: "https://github.com/settings/ssh/new",
    registerNote: "Add this to your GitHub account — any title you like. Until you do, it opens nothing.",
    check: verifyGithub,
    replaceCost: "The key on GitHub stops working. You'll paste a new one there.",
    removeCost: "Your spawns stop carrying a key. Remove it from GitHub too.",
  },
};

type State = { kind: "loading" } | { kind: "status"; status: CredentialStatus };
/** Which destructive action is one click from happening — the inline two-step, never a browser dialog. */
type Confirming = null | "replace" | "remove";

export function Credential({
  kind,
  onUnauthorized,
}: {
  kind: CredentialKind;
  onUnauthorized: () => void;
}) {
  const spec = SPECS[kind];
  const [state, setState] = useState<State>({ kind: "loading" });
  const [editing, setEditing] = useState(false);
  const [draft, setDraft] = useState("");
  const [busy, setBusy] = useState(false);
  const [confirming, setConfirming] = useState<Confirming>(null);
  const [copied, setCopied] = useState(false);
  const [check, setCheck] = useState<GithubCheck | null>(null);
  const [checking, setChecking] = useState(false);
  // Save/Remove name what failed rather than swallow it — otherwise you can't tell whether your
  // key is actually stored.
  const [error, setError] = useState<string | null>(null);

  const load = useCallback(() => {
    getCredential(kind)
      .then((status) => setState({ kind: "status", status }))
      .catch((e) => {
        if (e instanceof Unauthorized) return onUnauthorized();
        setError(`Couldn't read your ${spec.label} — ${errMessage(e)}`);
      });
  }, [kind, spec.label, onUnauthorized]);

  useEffect(() => { load(); }, [load]);

  const save = async () => {
    const value = draft.trim();
    if (!value) return;
    setBusy(true);
    setError(null);
    try {
      await setCredential(kind, value);
      setEditing(false);
      setDraft("");
      load();
    } catch (e) {
      if (e instanceof Unauthorized) return onUnauthorized();
      setError(`Couldn't save your ${spec.label} — ${errMessage(e)} It wasn't stored.`);
    } finally {
      setBusy(false);
    }
  };

  /** Mint, and show what came back. The reply IS the new public key — there is no second read. */
  const mint = async () => {
    setBusy(true);
    setError(null);
    setCheck(null);
    try {
      setState({ kind: "status", status: await mintCredential(kind) });
      setConfirming(null);
    } catch (e) {
      if (e instanceof Unauthorized) return onUnauthorized();
      setError(`Couldn't mint your ${spec.label} — ${errMessage(e)} Nothing changed.`);
    } finally {
      setBusy(false);
    }
  };

  const remove = async () => {
    setError(null);
    setConfirming(null);
    setCheck(null);
    try {
      await deleteCredential(kind);
      load();
    } catch (e) {
      if (e instanceof Unauthorized) return onUnauthorized();
      setError(`Couldn't remove the ${spec.label} — ${errMessage(e)}`);
    }
  };

  const copy = async (text: string) => {
    try {
      await navigator.clipboard.writeText(text);
      setCopied(true);
      window.setTimeout(() => setCopied(false), 1500);
    } catch {
      // No clipboard (an insecure origin, a browser that refuses) — the key is on screen and
      // selectable, so say that rather than leaving a button that does nothing.
      setError("Couldn't reach the clipboard — select the key above and copy it yourself.");
    }
  };

  const runCheck = async (fn: () => Promise<GithubCheck>) => {
    setChecking(true);
    setError(null);
    try {
      setCheck(await fn());
    } catch (e) {
      if (e instanceof Unauthorized) return onUnauthorized();
      setError(`Couldn't check — ${errMessage(e)}`);
    } finally {
      setChecking(false);
    }
  };

  const stored = state.kind === "status" && state.status.set;

  return (
    <div>
      {/* Label and every action on ONE row, the same header idiom PasswordForm uses — the actions belong
          to the thing named beside them, not to the value below. They light gold on hover like FactRow,
          so this module stops being the one place on the page where a control reads as bare text. */}
      <div className="mb-2 flex items-center justify-between gap-3">
        <Tip className="label" text={spec.tip}>{spec.label}</Tip>
        {stored && !editing && (
          confirming === null ? (
            <div className="flex items-center gap-2">
              <button
                className="btn-ghost btn-ghost-gold"
                disabled={busy}
                onClick={() => (spec.origin === "paste" ? setEditing(true) : setConfirming("replace"))}
              >
                Replace
              </button>
              <button
                className="btn-ghost btn-ghost-alarm"
                disabled={busy}
                onClick={() => (spec.origin === "paste" ? remove() : setConfirming("remove"))}
              >
                Remove
              </button>
            </div>
          ) : (
            /* The inline two-step, the same one CancelSpawn uses: it NAMES THE CONSEQUENCE instead of
               asking "are you sure?". Minted only — replacing a pasted key costs nothing but a paste,
               while replacing a minted one silently breaks every Spawn until GitHub is updated. */
            <div className="flex items-center gap-2">
              <span className="hidden text-[12px] text-ink-mute sm:inline">
                {confirming === "replace"
                  ? (spec as MintSpec).replaceCost
                  : (spec as MintSpec).removeCost}
              </span>
              <button className="btn-ghost" disabled={busy} onClick={() => setConfirming(null)}>
                Keep
              </button>
              <button
                className="btn-ghost"
                style={{ color: "var(--alarm)" }}
                disabled={busy}
                onClick={() => (confirming === "replace" ? mint() : remove())}
              >
                {confirming === "replace" ? (busy ? "Minting…" : "Mint a new one") : "Remove"}
              </button>
            </div>
          )
        )}
      </div>

      {error && <p role="alert" className="mb-2 text-[12px]" style={{ color: "var(--alarm)" }}>{error}</p>}

      {/* The load failing leaves this stuck on "loading" forever, so the error above replaces the
          spinner line rather than sitting beneath a promise that will never resolve. */}
      {state.kind === "loading" && !error && <p className="text-[13px] text-ink-mute">Loading…</p>}

      {state.kind === "status" && spec.origin === "paste" && (
        editing || !state.status.set ? (
          <div className="space-y-2">
            <div className="flex flex-wrap items-center gap-2">
              <input
                className="field min-w-0 flex-1"
                autoFocus={editing}
                placeholder={spec.placeholder}
                value={draft}
                onChange={(e) => setDraft(e.target.value)}
                onKeyDown={(e) => e.key === "Enter" && save()}
              />
              <button className="btn-primary shrink-0" disabled={busy || !draft.trim()} onClick={save}>
                {busy ? "Saving…" : "Save"}
              </button>
              {editing && (
                <button className="btn-ghost shrink-0" onClick={() => { setEditing(false); setDraft(""); }}>
                  Cancel
                </button>
              )}
            </div>
            {!state.status.set && (
              <p className="text-[12px] text-ink-mute">{spec.invitation}</p>
            )}
          </div>
        ) : (
          /* Just the hint now — its actions moved up into the header row above, and there is no
             third one: Reveal is gone because the Head has nothing to reveal. */
          <span className="num text-[13px] text-ink-soft">{spec.masked(state.status.hint ?? "")}</span>
        )
      )}

      {state.kind === "status" && spec.origin === "mint" && (
        !state.status.set ? (
          <div className="space-y-2">
            <button className="btn-primary" disabled={busy} onClick={mint}>
              {busy ? "Minting…" : spec.mintLabel}
            </button>
            <p className="text-[12px] text-ink-mute">{spec.invitation}</p>
          </div>
        ) : (
          <div className="space-y-2">
            {/* In full, wrapping, and selectable. This is the one Credential value that is MEANT to
                leave the page — a truncated public key is a key nobody can register. */}
            <p
              className="num break-all rounded-[10px] px-3 py-2 text-[12px] text-ink"
              style={{ background: "color-mix(in oklab, var(--well) 70%, black)" }}
            >
              {state.status.hint}
            </p>
            <div className="flex flex-wrap items-center gap-2">
              <button className="btn-ghost" onClick={() => copy(state.status.hint ?? "")}>
                {copied ? "Copied" : "Copy"}
              </button>
              <a
                className="btn-ghost btn-ghost-gold"
                href={spec.registerUrl}
                target="_blank"
                rel="noreferrer noopener"
              >
                Add to GitHub
              </a>
              {spec.check && (
                <button className="btn-ghost" disabled={checking} onClick={() => runCheck(spec.check!)}>
                  {checking ? "Checking…" : "Check it's registered"}
                </button>
              )}
            </div>
            {/* Three answers, never two: "we couldn't ask" must not read as "you haven't added it
                yet", which would send someone to GitHub to fix a Head with no route out. */}
            {check === null ? (
              <p className="text-[12px] text-ink-mute">{spec.registerNote}</p>
            ) : check.status === "ok" ? (
              <p className="text-[12px] text-ink-soft">
                GitHub accepts it — authenticated as <span className="num">{check.username}</span>.
              </p>
            ) : check.status === "unregistered" ? (
              /* Gold, not alarm: nothing is broken, something is unfinished. */
              <p className="text-[12px]" style={{ color: "var(--gold)" }}>
                GitHub doesn't know this key yet — add it above, then check again.
              </p>
            ) : (
              <p className="text-[12px]" style={{ color: "var(--alarm)" }}>
                Couldn't ask GitHub — {check.detail}. The key is stored either way.
              </p>
            )}
          </div>
        )
      )}
    </div>
  );
}
